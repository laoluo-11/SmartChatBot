/* =========================================================================
 * wake.h —— 离线唤醒词（ESP-SR wakenet）封装模块（L8 新增）
 * -------------------------------------------------------------------------
 * 设计意图：
 *   把"说一句唤醒词就能开始对话"这件事封装成两个简单函数：
 *     wake_init()   ：初始化唤醒词引擎（加载模型）
 *     wake_feed()   ：喂一段麦克风 PCM，返回"是否检测到唤醒词"
 *
 * 关键点：本模块对 esp-sr 组件做【编译期探测】——
 *   - 装了 esp-sr（且在 menuconfig 选了 WakeNet 模型）→ 走【真·离线唤醒词】，
 *     wake_feed() 会用神经网络检测唤醒词，命中返回 true。
 *   - 没装 esp-sr → 走【模拟模式】：wake_feed() 永远返回 false，
 *     工程照样能编译、运行（只是不能语音唤醒，只能按唤醒键）。
 *   这样无论你装不装组件，本工程都能编过；想体验真唤醒词，按 README 的 L8 章节
 *   装上 esp-sr + 选模型即可，不用改任何业务代码。
 *
 * 喂数据的约定（和 mic 模块对齐）：
 *   每段 PCM 是 16kHz、单声道、16bit 有符号；建议每帧 512 样本（约 32ms），
 *   正好和 mic.c 里的 MIC_READ_SAMPLES 一致。wakenet 内部按 30ms 帧处理，
 *   512 样本/帧是官方推荐的喂法。
 * ========================================================================= */

#pragma once
#include <stdbool.h>
#include <stdint.h>

/* 初始化唤醒词引擎。
 * 返回 true  = 已加载真实模型，离线唤醒词可用；
 * 返回 false = 未加载（没装 esp-sr / 没选模型 / 加载失败），将走模拟模式。 */
bool wake_init(void);

/* 喂一段 16kHz 单声道 int16 PCM；返回 true 表示检测到唤醒词。
 * buf     : 音频样本数组（不会在内部被修改，但 ESP-SR 旧接口可能要求非 const，已强转）
 * samples : 样本个数（不是字节数）
 * 建议每次喂 MIC_READ_SAMPLES(512) 个样本。 */
bool wake_feed(const int16_t *buf, int samples);

/* 反初始化（一般整个生命周期不需要，留着以防将来要热卸载模型）。 */
void wake_deinit(void);
